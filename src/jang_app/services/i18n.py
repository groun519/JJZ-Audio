def normalize_language(value: object) -> str:
    return value if isinstance(value, str) and value in SUPPORTED_LANGUAGES else LANGUAGE_KOREAN


def set_language(language: str) -> None:
    global _current_language
    _current_language = normalize_language(language)


def current_language() -> str:
    return _current_language


def has_translation(text: str) -> bool:
    return text in _KOREAN or any(text.startswith(prefix) for prefix in _KOREAN_PREFIXES)


def tr(text: str, **values: object) -> str:
    template = text
    if _current_language == LANGUAGE_KOREAN:
        template = _KOREAN.get(text, _translate_prefix(text))
    return template.format(**values) if values else template


def _translate_prefix(text: str) -> str:
    for source, translated in _KOREAN_PREFIXES.items():
        if text.startswith(source):
            return f"{translated}{text.removeprefix(source)}"
    return text
